const router = require('express').Router();
const { protect, restrictTo } = require('../middlewares/authMiddleware');
const { requireExamFees } = require('../middlewares/examFeeMiddleware');
const c = require('../controllers/examFeeController');
router.use(protect, restrictTo('admin', 'teacher'));
// Settings remain accessible when disabled; no ordinary-fee/private-school middleware.
router.get('/settings', restrictTo('admin'), c.getSettings);
router.patch('/settings', restrictTo('admin'), c.updateSettings);
router.use(requireExamFees);
router.get('/campaigns', c.campaigns);
router.get('/assignments', c.assignments);
router.get('/charges', c.charges);
router.get('/payments', c.history);
router.post('/payments', c.recordPayment);
router.get('/payments/:paymentId/receipt', c.receipt);
router.get('/remittances', c.remittances);
router.post('/remittances', restrictTo('teacher'), c.submitRemittance);
router.get('/collector-summary', c.collectorSummary);
router.use(restrictTo('admin'));
router.post('/campaigns', c.createCampaign);
router.patch('/campaigns/:campaignId', c.editCampaign);
router.post('/campaigns/:campaignId/activate', c.activate);
router.post('/campaigns/:campaignId/close', c.close);
router.post('/campaigns/:campaignId/assignments', c.assign);
router.post('/assignments/:assignmentId/revoke', c.revoke);
router.post('/charges/:chargeId/adjustments', c.adjust);
router.post('/payments/:paymentId/reverse', c.reverse);
router.post('/remittances/:remittanceId/confirm', c.confirmRemittance);
router.post('/remittances/:remittanceId/reject', c.rejectRemittance);
router.get('/reports', c.report);
router.get('/audit', c.audit);
module.exports = router;
